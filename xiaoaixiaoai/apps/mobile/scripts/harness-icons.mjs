#!/usr/bin/env node
/**
 * Regenerates src/lib/harnessIcons.ts from Uniflo's harness icon sprite
 * (`<svg id="harness-icons">` in Uniflo's crates/uniflo-gateway/src/index.html,
 * the same symbols its `GET /v1/harnesses/<id>/icon.svg` serves).
 *
 *   node scripts/harness-icons.mjs <path/to/uniflo/crates/uniflo-gateway/src/index.html>
 *
 * Only glyphs whose source licence allows redistribution are kept (MIT); see
 * THIRD_PARTY_NOTICES.md. When Uniflo adds a glyph, check its source there
 * (Uniflo's THIRD_PARTY_NOTICES.md) before adding the id to LICENSED.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** Harness id -> where the glyph comes from (all MIT). */
const LICENSED = {
  antigravity: "lobe-icons",
  claude: "lobe-icons",
  cline: "lobe-icons",
  codebuddy: "lobe-icons",
  codex: "lobe-icons",
  commandcode: "lobe-icons",
  copilot: "lobe-icons",
  cursor: "lobe-icons",
  devin: "lobe-icons",
  dsh: "lobe-icons (deepseek)",
  gemini: "lobe-icons",
  grok: "lobe-icons",
  hermes: "lobe-icons",
  kilo: "lobe-icons",
  kimi: "lobe-icons",
  kiro: "lobe-icons",
  mimocode: "lobe-icons",
  minimax: "lobe-icons",
  opencode: "lobe-icons",
  openclaw: "lobe-icons",
  pi: "lobe-icons",
  qoder: "lobe-icons",
  qwen: "lobe-icons",
  roo: "lobe-icons",
  zcode: "lobe-icons",
  omp: "oh-my-pi (MIT)",
  reasonix: "DeepSeek-Reasonix (MIT)",
  // Everything else in the sprite is left out: vendor-site logos with no licence (workbuddy,
  // factory) or no usable shape (craft). The app asks the computer's Uniflo for those at
  // runtime (src/lib/harnessRemote.ts) and shows a letter until one arrives.
};

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/harness-icons.mjs <uniflo/crates/uniflo-gateway/src/index.html>");
  process.exit(2);
}
const html = readFileSync(src, "utf8");
const start = html.indexOf('<svg id="harness-icons"');
if (start < 0) throw new Error("no harness-icons sprite in " + src);
const sprite = html.slice(start, html.indexOf("</svg>", start));

const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

function paths(inner, groupTransform) {
  const out = [];
  for (const m of inner.matchAll(/<g\b([^>]*)>([\s\S]*?)<\/g>|<path\b([^>]*?)\/?>/g)) {
    if (m[2] !== undefined) {
      const t = attrs(m[1]).transform;
      out.push(...paths(m[2], [groupTransform, t].filter(Boolean).join(" ") || undefined));
      continue;
    }
    const a = attrs(m[3]);
    if (!a.d) throw new Error("path without d");
    const p = { d: a.d };
    // Uniflo's standalone documents default to evenodd; keep only what differs.
    if (a["fill-rule"] && a["fill-rule"] !== "evenodd") p.fillRule = a["fill-rule"];
    if (a["clip-rule"]) p.clipRule = a["clip-rule"];
    if (a.opacity) p.opacity = Number(a.opacity);
    const t = [groupTransform, a.transform].filter(Boolean).join(" ");
    if (t) p.transform = t;
    out.push(p);
  }
  return out;
}

const glyphs = {};
const skipped = [];
for (const m of sprite.matchAll(/<symbol id="hi-([^"]+)"([^>]*)>([\s\S]*?)<\/symbol>/g)) {
  const [, id, symAttrs, inner] = m;
  if (attrs(symAttrs).viewBox !== "0 0 24 24") throw new Error(`${id}: viewBox is not 0 0 24 24`);
  const leftover = inner.replace(/<g\b[^>]*>|<\/g>|<path\b[^>]*?\/?>/g, "").trim();
  if (leftover) throw new Error(`${id}: unexpected markup ${leftover.slice(0, 60)}`);
  if (!LICENSED[id]) {
    skipped.push(id);
    continue;
  }
  glyphs[id] = paths(inner);
}
for (const id of Object.keys(LICENSED)) if (!glyphs[id]) throw new Error(`${id}: listed as licensed but missing from the sprite`);

const body = Object.entries(glyphs)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, ps]) => `  ${/^[a-z]\w*$/.test(id) ? id : JSON.stringify(id)}: ${JSON.stringify(ps)},`)
  .join("\n");

const ts = `// Generated by scripts/harness-icons.mjs from Uniflo's harness icon sprite. Do not edit by hand.
// Monochrome brand glyphs on a 24x24 canvas; sources and licences in THIRD_PARTY_NOTICES.md.
// Trademarks belong to their owners; a glyph only identifies the harness it stands for.
// Marks that can't be bundled come from the computer at runtime (lib/harnessRemote.ts).

export interface GlyphPath {
  d: string;
  /** Default evenodd. */
  fillRule?: "evenodd" | "nonzero";
  clipRule?: "evenodd" | "nonzero";
  opacity?: number;
  transform?: string;
}

export const HARNESS_GLYPHS: Record<string, readonly GlyphPath[]> = {
${body}
};
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "harnessIcons.ts");
writeFileSync(out, ts);
console.log(`wrote ${Object.keys(glyphs).length} glyphs to ${out}; left out: ${skipped.join(", ") || "none"}`);
